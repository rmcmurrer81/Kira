#!/usr/bin/env python3
"""Render CPU-friendly MP3 dialogue at build time, never on a player's laptop.
Requires kokoro-onnx 0.6.1 from PyPI, FFmpeg, Node, and the public Kokoro v1.0
ONNX/voice files from https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0.
Pass --model and --voices paths. No private voice data or cloud synthesis.
"""
import argparse, concurrent.futures, hashlib, json, os, re, subprocess, tempfile, time, wave
from pathlib import Path
os.environ["ORT_DISABLE_TELEMETRY"]="1"  # Must precede onnxruntime initialization.
import numpy as np
import onnxruntime as rt
from kokoro_onnx import Kokoro
args=argparse.ArgumentParser();args.add_argument('--model',required=True);args.add_argument('--voices',required=True);args.add_argument('--workers',type=int,default=4);args=args.parse_args()
ROOT=Path(__file__).resolve().parents[1];GAME=ROOT/'docs/arcade/byte-bolt'
data=json.loads(subprocess.check_output(['node','-e',"const D=require('./docs/arcade/byte-bolt/dialogue.js');console.log(JSON.stringify([...new Set(D.allText().flatMap(D.segments))].sort()))"],cwd=ROOT))
OUT=GAME/'audio/narrator';OUT.mkdir(exist_ok=True)
options=rt.SessionOptions();options.intra_op_num_threads=1;options.inter_op_num_threads=1
rt.disable_telemetry_events()
model=Kokoro.from_session(rt.InferenceSession(args.model,sess_options=options,providers=['CPUExecutionProvider']),args.voices)
MODEL_HASH=hashlib.sha256(Path(args.model).read_bytes()).hexdigest()
VOICE_HASH=hashlib.sha256(Path(args.voices).read_bytes()).hexdigest()
def spoken(text):
    variables={'distanceCm':'distance in centimeters','durationUs':'duration in microseconds','speedCmPerUs':'speed in centimeters per microsecond','supplyV':'supply voltage','ledV':'L E D voltage','targetMa':'target milliamps','topOhms':'top resistance in ohms','bottomOhms':'bottom resistance in ohms','tempC':'temperature in degrees Celsius','energyWh':'energy in watt hours','voltageV':'voltage in volts','currentA':'current in amps','batteryPct':'battery percentage'}
    for old,new in variables.items():text=re.sub(r'\b'+old+r'\b',new,text)
    for old,new in [('°C',' degrees Celsius'),('mA','milliamps'),('LED','L E D'),('E12','E twelve'),('PWM','P W M'),('ADC','A D C'),('GPIO','G P I O'),(' · ', ', '),(' → ', ' to '),('×',' times '),('%',' percent'),('Ω',' ohms'),('’',"'"),('−',' minus ')]:text=text.replace(old,new)
    return re.sub(r'([a-z])([A-Z])',r'\1 \2',text)
def build(text):
    speech=spoken(text);name=hashlib.sha256(('kokoro-v1-af_sarah\0'+MODEL_HASH+'\0'+speech).encode()).hexdigest()[:20]+'.mp3';target=OUT/name
    if not target.exists():
      audio,sr=model.create(speech,voice='af_sarah',speed=1.0,lang='en-us')
      if len(audio)<sr*.15 or not np.isfinite(audio).all() or np.max(np.abs(audio))<.01:raise ValueError('Invalid audio for '+text)
      with tempfile.TemporaryDirectory() as tmp:
        file=Path(tmp)/'speech.wav'
        with wave.open(str(file),'wb') as f:f.setnchannels(1);f.setsampwidth(2);f.setframerate(sr);f.writeframes((np.clip(audio,-1,1)*32767).astype('<i2').tobytes())
        subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-i',str(file),'-af','loudnorm=I=-19:TP=-2:LRA=7','-ac','1','-ar','24000','-codec:a','libmp3lame','-b:a','64k','-map_metadata','-1','-y',str(target)],check=True)
    return text,'audio/narrator/'+name
mapping={};started=time.time()
with concurrent.futures.ThreadPoolExecutor(max_workers=args.workers) as pool:
    for text,src in pool.map(build,data):
        mapping[text]=src
        if len(mapping)%20==0:print(f'{len(mapping)}/{len(data)} clips ready ({time.time()-started:.0f}s)',flush=True)
(GAME/'audio-bundled-map.js').write_text('/* Generated by scripts/build_byte_bolt_audio.py. Do not hand-edit. */\nwindow.TOWN_BUNDLED_AUDIO='+json.dumps(mapping,ensure_ascii=False,indent=2)+';\n')
manifest={'engine':'Kokoro v1.0 via kokoro-onnx 0.6.1; CPU build-time rendering','voice':'af_sarah (stock licensed voice, not a clone or recreation of a game character)','model_sha256':MODEL_HASH,'voices_sha256':VOICE_HASH,'generated_locally':True,'runtime_synthesis':False,'private_voice_data':False,'format':'mono MP3, 24 kHz, 64 kbps','segments':[{'caption':t,'spoken_text':spoken(t),'src':src} for t,src in mapping.items()]}
(OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print(f'{len(mapping)} clips, {sum(p.stat().st_size for p in OUT.glob("*.mp3")):,} audio bytes',flush=True)
